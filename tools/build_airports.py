"""Build airports.js (offline airport database) from the airportsdata package (MIT).

    pip download airportsdata --no-deps -d /tmp/ad && unzip -o /tmp/ad/*.whl -d /tmp/ad
    python3 -I tools/build_airports.py /tmp/ad/airportsdata/airports.csv 20261103

(reads the CSV as data; the package's code is never run)

Keeps every airport with an IATA code (airline-served airports), sorted by IATA.
Row format: ICAO|IATA|name|city|country|lat|lon|tz-index
"""
import csv, json, os, re, sys, datetime
src, ver = sys.argv[1], sys.argv[2]
rows = [r for r in csv.DictReader(open(src, encoding="utf-8")) if re.fullmatch(r"[A-Z]{3}", r["iata"] or "")]
seen, out, tzs = set(), [], []
def tzi(z):
    if z not in tzs: tzs.append(z)
    return tzs.index(z)
def short(n):
    n = re.sub(r"\s+Airport$", "", n.strip())
    n = re.sub(r"\bInternational\b", "Intl", n)
    return n.replace("|", "/")
for r in sorted(rows, key=lambda r: (r["iata"], r["icao"])):
    if r["iata"] in seen: continue
    seen.add(r["iata"])
    icao = r["icao"] if re.fullmatch(r"[A-Z]{4}", r["icao"] or "") else ""
    out.append("|".join([icao, r["iata"], short(r["name"]), (r["city"] or "").replace("|", "/"), r["country"],
                         f'{float(r["lat"]):.4f}'.rstrip("0").rstrip("."), f'{float(r["lon"]):.4f}'.rstrip("0").rstrip("."), str(tzi(r["tz"]))]))
js = ("/* Airport database: %d airports with IATA codes. Generated by tools/build_airports.py from the\n"
      " * airportsdata package %s (MIT License, https://github.com/mborsetti/airportsdata). Do not edit. */\n"
      "window.SolatAirports = { version: %s, tz: %s,\n  data: %s };\n") % (
      len(out), ver, json.dumps(ver), json.dumps(tzs, separators=(",", ":")), json.dumps("\n".join(out)))
open(os.path.join(os.path.dirname(__file__), "..", "airports.js"), "w", encoding="utf-8").write(js)
print(len(out), "airports,", len(tzs), "zones,", len(js), "bytes")
